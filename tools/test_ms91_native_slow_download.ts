import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {decodeVersionedReplay} from '../lib/game/versioned-replay-file.ts';
import {nativeFileDownload} from '../lib/game/native-file-download.ts';
import {encodeSaveBackup,decodeSaveBackup} from '../lib/game/save-backup.ts';
import {prepareReplayUpload} from '../lib/game/replay-upload.ts';
const [path]=process.argv.slice(2);if(!path)throw Error('Provide the original MS91 10 Hz DEFAULT.RPL; do not silently skip');
const original=new Uint8Array(readFileSync(path)),before=original.slice(),decoded=decodeVersionedReplay(original,'ms-1991');
assert.equal(decoded.framesPerSecond,10);
const canonical=decoded.bytes.slice();
const output=nativeFileDownload({key:'C:\\DEFAULT.RPL',bytes:canonical,physicsEngine:'ms-1991',framesPerSecond:10});
assert.deepEqual(output,original,'Native slow download reproduces every original file byte, not only normalized controls');
assert.throws(()=>prepareReplayUpload('DEFAULT.RPL',output,'C:\\','ms-1991'),/Only 20 Hz/);
const imported=prepareReplayUpload('DEFAULT.RPL',output,'C:\\','ms-1991',{experimentalMs91Slow:true});
assert.equal(imported.framesPerSecond,10);assert.equal(imported.physicsEngine,'ms-1991');assert.deepEqual(imported.bytes,canonical);
assert.deepEqual(nativeFileDownload(imported),original,'Experimental import retains timing and exact original external bytes');
assert.throws(()=>prepareReplayUpload('DEFAULT.RPL',output,'C:\\','bb-1991',{experimentalMs91Slow:true}),/Only 20 Hz/);
assert.deepEqual(canonical,decoded.bytes);assert.deepEqual(new Uint8Array(readFileSync(path)),before);
const old=new Uint8Array(readFileSync('public/game/replays/CTKFIN.RPL')),legacyScores=new Uint8Array(364).fill(37);
const stored=[{key:'C:\\OLD.RPL',bytes:old},{key:'C:\\DEFAULT.HIG',bytes:legacyScores},{key:'C:\\DEFAULT.RPL',bytes:canonical,physicsEngine:'ms-1991' as const,framesPerSecond:10 as const}];
const snapshot=structuredClone(stored),backup=encodeSaveBackup(stored,'C:\\'),restored=decodeSaveBackup(backup);
assert.deepEqual(restored.files,stored);
const slow=restored.files.find(file=>file.key==='C:\\DEFAULT.RPL');assert.ok(slow);
assert.deepEqual(nativeFileDownload(slow),original,'Backup-restored slow replay exports the exact original file');
assert.deepEqual(nativeFileDownload(restored.files.find(file=>file.key==='C:\\OLD.RPL')!),old);
assert.deepEqual(restored.files.find(file=>file.key==='C:\\DEFAULT.HIG')!.bytes,legacyScores);
assert.deepEqual(stored,snapshot);assert.equal(encodeSaveBackup(stored,'C:\\'),backup);
console.log('MS91 private 10 Hz export is byte-identical to the original slow reference; canonical recording and source file unchanged');
console.log('Mixed backup restoration retains slow cadence, exact downloads, untagged legacy replays and legacy score bytes');
