import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=mkdtempSync(join(tmpdir(),'stunts-oracle-package-'));
const replay=Buffer.alloc(0x724+3),capture=Buffer.alloc(2+3*1120);
replay.writeUInt16LE(3,24);capture.writeUInt16LE(3);
const hash=b=>createHash('sha256').update(b).digest('hex');
const paths=['QA.RPL','capture.bin','proof.json'].map(name=>join(root,name));
writeFileSync(paths[0],replay);writeFileSync(paths[1],capture);
writeFileSync(paths[2],JSON.stringify({frames:3,replaySha256:hash(replay),captureSha256:hash(capture)}));
const run=(target,inputs=paths)=>spawnSync(process.execPath,['tools/package_replay_oracle_evidence.mjs',target,...inputs],{encoding:'utf8'});
const target=join(root,'preserved');assert.equal(run(target).status,0);
const manifest=readFileSync(join(target,'manifest.json'));
assert.equal(JSON.parse(manifest).productionDatabaseIncluded,false);
assert.deepEqual(readFileSync(join(target,'QA.RPL')),replay);
assert.notEqual(run(target).status,0,'Existing evidence must not be overwritten');
assert.deepEqual(readFileSync(join(target,'manifest.json')),manifest);
replay[replay.length-1]=1;writeFileSync(paths[0],replay);
const corrupt=join(root,'corrupt');assert.notEqual(run(corrupt).status,0);
assert.equal(existsSync(corrupt),false,'Hash failure must precede any output');
writeFileSync(paths[0],Buffer.alloc(1));
const short=join(root,'short');assert.notEqual(run(short).status,0);assert.equal(existsSync(short),false);
assert.notEqual(run('relative-path').status,0);
console.log(JSON.stringify({copyVerified:true,overwriteRejected:true,corruptInputRejectedBeforeOutput:true,syntheticTestOnly:true}));
