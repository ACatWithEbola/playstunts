import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtempSync,writeFileSync,linkSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {compareSnapshots,inspectSnapshot} from './compare_database_restore.mjs';
const root=mkdtempSync(join(tmpdir(),'stunts-db-restore-'));
const create=(name,reverse=false)=>{
 const path=join(root,name+'.sqlite'),db=new DatabaseSync(path);
 db.exec('CREATE TABLE recordings(id INTEGER,replay BLOB,metadata TEXT);CREATE INDEX by_id ON recordings(id)');
 db.exec('CREATE TABLE ids(id INTEGER PRIMARY KEY AUTOINCREMENT);INSERT INTO ids DEFAULT VALUES;DELETE FROM ids;CREATE TABLE reals(value REAL)');
 db.prepare('INSERT INTO reals VALUES (?)').run(Infinity);
 const rows=[[9007199254740993n,new Uint8Array([0,255,31]),'legacy'],[2n,new Uint8Array([2,0]),null],[2n,new Uint8Array([2,0]),null]];
 for(const row of reverse?rows.reverse():rows)db.prepare('INSERT INTO recordings VALUES (?,?,?)').run(...row);
 db.close();return path;
};
const source=create('source'),restored=create('restored',true);
assert.equal(compareSnapshots(source,restored).allStoredValuesMatch,true,'Row order does not matter; duplicates and 64-bit integers do');
assert.equal(compareSnapshots(source,restored).sourceCompletenessVerified,false);
assert.throws(()=>compareSnapshots(source,source),/Independent/);
const alias=join(root,'alias.sqlite');linkSync(source,alias);
assert.throws(()=>compareSnapshots(source,alias),/Independent/,'A hard link is not an independent restoration');
const change=(sql)=>{const db=new DatabaseSync(restored);db.exec(sql);db.close();};
change("UPDATE recordings SET replay=X'00FF20' WHERE metadata='legacy'");
assert.throws(()=>compareSnapshots(source,restored),/differ/,'One raw replay byte must fail restoration');
change("UPDATE recordings SET replay=X'00FF1F' WHERE metadata='legacy'");
assert.equal(compareSnapshots(source,restored).allStoredValuesMatch,true);
change('UPDATE sqlite_sequence SET seq=100');assert.throws(()=>compareSnapshots(source,restored),/differ/,'Internal sequence state must survive restore');
change('UPDATE sqlite_sequence SET seq=1');
const floating=new DatabaseSync(restored);floating.prepare('UPDATE reals SET value=?').run(-Infinity);floating.close();
assert.throws(()=>compareSnapshots(source,restored),/differ/,'Positive and negative infinity cannot collapse to the same JSON null');
const repair=new DatabaseSync(restored);repair.prepare('UPDATE reals SET value=?').run(Infinity);repair.close();
change('DROP INDEX by_id');assert.throws(()=>compareSnapshots(source,restored),/differ/,'Indexes are part of restoration');
writeFileSync(source+'-wal',new Uint8Array(),{flag:'wx'});
assert.throws(()=>inspectSnapshot(source),/sidecars/);
console.log('Offline restoration compares exact raw bytes, duplicate rows, 64-bit integers and schema; source completeness remains separate');
