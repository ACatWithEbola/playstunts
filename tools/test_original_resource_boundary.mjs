import assert from 'node:assert/strict';
import {readFileSync,mkdtempSync,mkdirSync,writeFileSync} from 'node:fs';
import {execFileSync,spawnSync} from 'node:child_process';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {originalResourceBoundaryFindings} from './check_original_resource_boundary.mjs';
const recipes=JSON.parse(readFileSync(new URL('../docs/ms91-resource-recipes.json',import.meta.url)));
assert.equal(recipes.outputs.length,7);
const paths=recipes.outputs.map(row=>'lib/game/'+row.path);
for(const path of paths)assert.deepEqual(originalResourceBoundaryFindings(['README.md',path],recipes),[path]);
assert.deepEqual(originalResourceBoundaryFindings(['lib/game/versioned-title-resource.ts','docs/ms91-resource-recipes.json'],recipes),[]);
const ignored=execFileSync('git',['check-ignore','--no-index',...paths],{encoding:'utf8'}).trim().split('\n');
assert.deepEqual(ignored.sort(),paths.sort());
const scratch=mkdtempSync(join(tmpdir(),'stunts-source-boundary-'));
const script=fileURLToPath(new URL('./check_original_resource_boundary.mjs',import.meta.url));
const withoutIndex=spawnSync(process.execPath,[script],{cwd:scratch,encoding:'utf8'});
assert.notEqual(withoutIndex.status,0,'Publication checks cannot silently approve an archive without an index');
const localArchive=spawnSync(process.execPath,[script,'--local-build'],{cwd:scratch,encoding:'utf8'});
assert.equal(localArchive.status,0,localArchive.stderr);
assert.match(localArchive.stdout,/publication boundary is not verified/);
execFileSync('git',['init','--quiet',scratch]);mkdirSync(join(scratch,'lib/game'),{recursive:true});
writeFileSync(join(scratch,paths[0]),'{}\n');
execFileSync('git',['add','--force',paths[0]],{cwd:scratch});
const checked=spawnSync(process.execPath,[fileURLToPath(new URL('./check_original_resource_boundary.mjs',import.meta.url))],{cwd:scratch,encoding:'utf8'});
assert.equal(checked.status,1);assert.ok(checked.stderr.includes(paths[0]));
const localStaged=spawnSync(process.execPath,[script,'--local-build'],{cwd:scratch,encoding:'utf8'});
assert.equal(localStaged.status,1,'Local build mode must still reject force-staged original resources');
console.log('All seven generated resource paths are ignored and force-staged originals fail the publication boundary');
