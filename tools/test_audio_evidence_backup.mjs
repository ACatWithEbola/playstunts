import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,existsSync,symlinkSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {execFileSync} from 'node:child_process';
const root=mkdtempSync(join(tmpdir(),'audio-evidence-backup-test-'));
const source=join(root,'source','a');mkdirSync(source,{recursive:true});
writeFileSync(join(source,'manifest.json'),'{}');writeFileSync(join(source,'trial.wav'),Buffer.from([1,2,3,4]));
const run=(target,...sources)=>execFileSync(process.execPath,['tools/backup_audio_trial_evidence.mjs',target,...sources],{encoding:'utf8',stdio:['pipe','pipe','pipe']});
const destination=join(root,'copy'),result=JSON.parse(run(destination,source));
assert.equal(result.fileCount,2);assert.equal(result.productionDatabaseIncluded,false);assert.equal(result.renderedLayerInputsIncluded,false);
assert.deepEqual(readFileSync(join(destination,'files','a','trial.wav')),Buffer.from([1,2,3,4]));
assert.throws(()=>run(destination,source),'Existing backup cannot be overwritten');
const duplicate=join(root,'another','a');mkdirSync(duplicate,{recursive:true});
writeFileSync(join(duplicate,'manifest.json'),'{}');
assert.throws(()=>run(join(root,'duplicate'),source,duplicate));assert.ok(!existsSync(join(root,'duplicate')));
const linked=join(root,'linked');symlinkSync(source,linked);
assert.throws(()=>run(join(root,'symlink-copy'),linked));assert.ok(!existsSync(join(root,'symlink-copy')));
writeFileSync(join(source,'unexpected.txt'),'not approved evidence');
assert.throws(()=>run(join(root,'wrong-files'),source));assert.ok(!existsSync(join(root,'wrong-files')));
console.log('Evidence copy verifies bytes and scope; existing destinations, duplicate folders, symlinks and unexpected files reject before writing');
